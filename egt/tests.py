from otree.api import Currency as c, currency_range
from . import pages
from ._builtin import Bot
from .models import Constants
import random

# **********************************************************************************************************************
# *** BOT
# **********************************************************************************************************************
class PlayerBot(Bot):

    def play_round(self):

        # define page as round_number
        page = self.subsession.round_number

        # ------------------------------------------------------------------------------------------------------------ #
        # submit instructions page
        # ------------------------------------------------------------------------------------------------------------ #
        if page == 1:
            yield pages.Instructions

        # ------------------------------------------------------------------------------------------------------------ #
        # submit practice page
        # ------------------------------------------------------------------------------------------------------------ #
        if page == 1:
            yield pages.Practice

        # ------------------------------------------------------------------------------------------------------------ #
        # make decisions
        # ------------------------------------------------------------------------------------------------------------ #
        choice_set = Constants.choices[page - 1]
        yield (pages.Decision, {'choice': random.choice(choice_set)})
